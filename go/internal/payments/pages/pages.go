// ---- small Python equivalents ----------------------------------------------

// stripeMode is config.STRIPE_MODE.
func stripeMode(getenv func(string) string) string {
	return strings.ToLower(strings.TrimSpace(getenv("UBYHOST_STRIPE_MODE")))
}

// stripeOff is payments._off.
func stripeOff(getenv func(string) string) bool {
	m := stripeMode(getenv)
	return m != "test" && m != "live"
}

// pySpace is str.isspace for one rune: unicode.IsSpace plus \x1c-\x1f.
func pySpace(r rune) bool { return unicode.IsSpace(r) || (r >= 0x1c && r <= 0x1f) }

// pyStrip is str.strip().
func pyStrip(s string) string { return strings.TrimFunc(s, pySpace) }

// asciiDigits is str.isdigit for ASCII input (Python also takes other
// Unicode digits; the existing Go payment routes make the same choice).
func asciiDigits(s string) bool {
	if s == "" {
		return false
	}
	for _, c := range s {
		if c < '0' || c > '9' {
			return false
		}
	}
	return true
}

// lastQuery is request.query_params.get: the last value, and whether the key is there.
func lastQuery(r *http.Request, key string) (string, bool) {
	v, ok := r.URL.Query()[key]
	if !ok || len(v) == 0 {
		return "", ok
	}
	return v[len(v)-1], true
}

// lastForm is Starlette's form.get: the last value of a field.
func lastForm(r *http.Request, key string) string {
	if err := r.ParseForm(); err != nil {
		return ""
	}
	v := r.PostForm[key]
	if len(v) == 0 {
		return ""
	}
	return v[len(v)-1]
}

var isoDate = regexp.MustCompile(`^([0-9]{4})-([0-9]{1,2})-([0-9]{1,2})$`)

// dateCZ is validation.fmt_date (the date_cz filter): DD.MM.YYYY from the
// first ten characters, or the value unchanged.
func dateCZ(v string) string {
	head := v
	if r := []rune(v); len(r) > 10 {
		head = string(r[:10])
	}
	m := isoDate.FindStringSubmatch(head)
	if m == nil {
		return v
	}
	y, _ := strconv.Atoi(m[1])
	mo, _ := strconv.Atoi(m[2])
	d, _ := strconv.Atoi(m[3])
	t := time.Date(y, time.Month(mo), d, 0, 0, 0, 0, time.UTC)
	if y < 1 || t.Year() != y || int(t.Month()) != mo || t.Day() != d {
		return v
	}
	return fmt.Sprintf("%02d.%02d.%04d", d, mo, y)
}

// pyQuote is urllib.parse.quote(s) with the default safe="/".
func pyQuote(s string) string {
	const hexDigits = "0123456789ABCDEF"
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9', strings.IndexByte("_.-~/", c) >= 0:
			b.WriteByte(c)
		default:
			b.WriteByte('%')
			b.WriteByte(hexDigits[c>>4])
			b.WriteByte(hexDigits[c&15])
		}
	}
	return b.String()
}

// stampAt is db.utcnow() at the given time.
func stampAt(t time.Time) string {
	return t.UTC().Truncate(time.Second).Format("2006-01-02T15:04:05") + "+00:00"
}

func fail(w http.ResponseWriter, err error) {
	log.Printf("payments page failed: %v", err)
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.WriteHeader(http.StatusInternalServerError)
	_, _ = w.Write([]byte("Internal Server Error"))
}

func flash(r *http.Request, key string) hostweb.Flash {
	return hostweb.Flash{Text: cat.T(hostweb.Lang(r), key, nil), Key: key}
}

func backMsg(w http.ResponseWriter, r *http.Request, path, key string) {
	hostweb.Back(w, r, path, flash(r, key), hostweb.Flash{})
}

func backErr(w http.ResponseWriter, r *http.Request, path, key, fix string) {
	f := flash(r, key)
	f.Fix = fix
	hostweb.Back(w, r, path, hostweb.Flash{}, f)
}

func notFound(w http.ResponseWriter) { w.WriteHeader(http.StatusNotFound) }

func render(w http.ResponseWriter, r *http.Request, pool *pgxpool.Pool, getenv func(string) string, at time.Time,
	h *session.Host, p layout.Page, name string, data any) {
	p.Nav = "payments"
	p.HowKey = "payments"
	p.Title = cat.T(hostweb.Lang(r), p.Title, nil)
	var buf bufferedWriter
	buf.header = w.Header()
	if err := layout.Render(&buf, r, layout.Env{Pool: pool, Getenv: getenv, Now: at}, h, p, pages, name, data); err != nil {
		fail(w, err)
		return
	}
	w.WriteHeader(buf.code)
	_, _ = w.Write(buf.body.Bytes())
}

// bufferedWriter holds the page until Render succeeds, so a failed render is
// a clean 500 and never half a page.
type bufferedWriter struct {
	header http.Header
	code   int
	body   bytes.Buffer
}

func (b *bufferedWriter) Header() http.Header { return b.header }
func (b *bufferedWriter) WriteHeader(code int) {
	if b.code == 0 {
		b.code = code
	}
}
func (b *bufferedWriter) Write(p []byte) (int, error) {
	if b.code == 0 {
		b.code = http.StatusOK
	}
	return b.body.Write(p)
}

