type service struct {
	node   *node
	ID     string // the id when it is a string; get() matches only those
	Name   string
	Amount string
}

func servicesKey(owner int64) string { return fmt.Sprintf("payment_services:%d", owner) }

// listServices is payment_services.list_for: the dict items with a truthy id
// and name. Bad JSON, or JSON that is not a list, is no services.
func listServices(ctx context.Context, pool *pgxpool.Pool, owner int64) ([]service, error) {
	var raw *string
	err := pool.QueryRow(ctx, settingSQL, servicesKey(owner)).Scan(&raw)
	if err != nil && !errors.Is(err, pgx.ErrNoRows) {
		return nil, err
	}
	text := "[]"
	if raw != nil && *raw != "" {
		text = *raw
	}
	root, err := parseJSON(text)
	if err != nil || root.kind != 'a' {
		return nil, nil
	}
	var out []service
	for _, item := range root.items {
		if item.kind != 'o' || !item.get("id").truthy() || !item.get("name").truthy() {
			continue
		}
		s := service{node: item, Name: item.get("name").text(), Amount: item.get("amount_czk").text()}
		if id := item.get("id"); id.kind == 's' {
			s.ID = id.str
		} else {
			s.ID = id.text()
		}
		out = append(out, s)
	}
	return out, nil
}

// findService is payment_services.get.
func findService(list []service, id string) *service {
	for i := range list {
		if n := list[i].node.get("id"); n.kind == 's' && n.str == id {
			return &list[i]
		}
	}
	return nil
}

func saveServices(ctx context.Context, pool *pgxpool.Pool, owner int64, list []*node) error {
	var b bytes.Buffer
	(&node{kind: 'a', items: list}).dump(&b)
	_, err := pool.Exec(ctx, setSettingSQL, servicesKey(owner), b.String())
	return err
}

func nodes(list []service) []*node {
	out := make([]*node, 0, len(list)+1)
	for _, s := range list {
		out = append(out, s.node)
	}
	return out
}

var errService = errors.New("service refused")

// addService is payment_services.add.
func addService(ctx context.Context, pool *pgxpool.Pool, owner int64, name string, amount int64, amountOK bool) error {
	name = strings.Join(strings.FieldsFunc(name, pySpace), " ")
	if r := []rune(name); len(r) > maxName {
		name = string(r[:maxName])
	}
	if name == "" || !amountOK || amount < 1 || amount > maxAmount {
		return errService
	}
	list, err := listServices(ctx, pool, owner)
	if err != nil {
		return err
	}
	if len(list) >= maxServices {
		return errService
	}
	var raw [4]byte
	if _, err := rand.Read(raw[:]); err != nil {
		return err
	}
	item := &node{kind: 'o', keys: []string{"id", "name", "amount_czk"}, vals: []*node{
		{kind: 's', str: hex.EncodeToString(raw[:])},
		{kind: 's', str: name},
		{kind: 'n', num: strconv.FormatInt(amount, 10)},
	}}
	return saveServices(ctx, pool, owner, append(nodes(list), item))
}

// removeService is payment_services.remove.
func removeService(ctx context.Context, pool *pgxpool.Pool, owner int64, id string) error {
	list, err := listServices(ctx, pool, owner)
	if err != nil {
		return err
	}
	var kept []*node
	for _, s := range list {
		if n := s.node.get("id"); n.kind == 's' && n.str == id {
			continue
		}
		kept = append(kept, s.node)
	}
	if len(kept) == len(list) {
		return nil
	}
	if kept == nil {
		kept = []*node{}
	}
	return saveServices(ctx, pool, owner, kept)
}

// ---- reads -----------------------------------------------------------------------

func consentAccepted(ctx context.Context, pool *pgxpool.Pool, owner int64) (bool, error) {
	var id int64
	err := pool.QueryRow(ctx, consentSQL, owner, consentAction, "version="+consentVersion).Scan(&id)
	if errors.Is(err, pgx.ErrNoRows) {
		return false, nil
	}
	return err == nil, err
}

func hasBankAccount(ctx context.Context, pool *pgxpool.Pool, owner int64) (bool, error) {
	var iban, bank *string
	err := pool.QueryRow(ctx, bankSQL, owner).Scan(&iban, &bank)
	if errors.Is(err, pgx.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return (iban != nil && *iban != "") || (bank != nil && *bank != ""), nil
}

type stay struct {
	ID    int64
	Label string
}

// loadStays is payments._stays with _stay_label.
func loadStays(ctx context.Context, pool *pgxpool.Pool, owner int64) ([]stay, error) {
	rows, err := pool.Query(ctx, staysSQL, owner)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []stay
	for rows.Next() {
		var (
			s                        stay
			summary, from, to, apart string
		)
		if err := rows.Scan(&s.ID, &summary, &from, &to, &apart); err != nil {
			return nil, err
		}
		name := pyStrip(summary)
		if name == "" {
			name = pyStrip(apart)
		}
		s.Label = fmt.Sprintf("%s (%s → %s)", name, from, to)
		out = append(out, s)
	}
	return out, rows.Err()
}

// ---- GET /payments ---------------------------------------------------------------

type step struct {
	Key, Status, Href string
	N                 int
	Cur, Help         bool
}

type entityView struct{ Name, Email string }

type requestView struct {
	ID                      int64
	Reason, Note, Status    string
	Amount                  int64
	NoStay                  bool
	Created, Tone           string
	CanLink, CanSend, HasQR bool
	ShowMenu, MenuSend      bool
}

type overviewData struct {
	StripeOff, Complete, Blocked bool
	State, Next                  string
	Steps                        []step
	Entity                       *entityView
	Services                     []service
	Requests                     []requestView
	HowSteps                     []int
}

func loadOverview(ctx context.Context, pool *pgxpool.Pool, getenv func(string) string, owner int64) (overviewData, error) {
	d := overviewData{StripeOff: stripeOff(getenv), State: "none", HowSteps: []int{1, 2, 3}}
	err := pool.QueryRow(ctx, accountSQL, owner, stripeMode(getenv)).Scan(&d.State)
	if err != nil && !errors.Is(err, pgx.ErrNoRows) {
		return d, err
	}
	d.Complete = d.State == "complete"
	d.Blocked = d.State == "rejected" || d.State == "disabled"

	// _setup
	consent, err := consentAccepted(ctx, pool, owner)
	if err != nil {
		return d, err
	}
	var (
		entityID    int64
		name, email string
		hasEntity   bool
		detailsHref = "/entities"
	)
	err = pool.QueryRow(ctx, entitySQL, owner).Scan(&entityID, &name, &email)
	switch {
	case err == nil:
		hasEntity = true
		detailsHref = fmt.Sprintf("/entities?edit=%d", entityID)
	case !errors.Is(err, pgx.ErrNoRows):
		return d, err
	}
	hasDetails := hasEntity && pyStrip(name) != ""
	stripeStatus := map[string]string{"pending": "waiting", "action_required": "attention"}[d.State]
	if stripeStatus == "" {
		stripeStatus = "todo"
	}
	status := func(ok bool) string {
		if ok {
			return "done"
		}
		return "todo"
	}
	d.Steps = []step{
		{Key: "consent", Status: status(consent)},
		{Key: "details", Status: status(hasDetails), Href: detailsHref},
		{Key: "stripe", Status: stripeStatus, Help: true},
		{Key: "live", Status: "todo", Help: true},
	}
	cur := ""
	for i := range d.Steps {
		d.Steps[i].N = i + 1
		if cur == "" && d.Steps[i].Status != "done" {
			cur = d.Steps[i].Key
			d.Steps[i].Cur = true
		}
	}
	switch {
	case !consent:
		d.Next = "consent"
	case !hasDetails:
		d.Next = "details"
	default:
		d.Next = "stripe"
	}
	if hasDetails {
		d.Entity = &entityView{Name: name, Email: email}
	}

	if d.Services, err = listServices(ctx, pool, owner); err != nil {
		return d, err
	}
	rows, err := pool.Query(ctx, requestsSQL, owner)
	if err != nil {
		return d, err
	}
	defer rows.Close()
	for rows.Next() {
		var (
			v           requestView
			rail, guest string
			created     string
		)
		if err := rows.Scan(&v.ID, &v.Reason, &v.Amount, &rail, &v.Status, &guest, &v.Note, &v.NoStay, &created); err != nil {
			return d, err
		}
		v.Created = dateCZ(created)
		switch v.Status {
		case "paid":
			v.Tone = "p-ok"
		case "sent", "awaiting_payment":
			v.Tone = "p-warn"
		default:
			v.Tone = "p-n"
		}
		open := v.Status == "draft" || v.Status == "sent" || v.Status == "awaiting_payment"
		v.CanLink = rail == "card" && open
		v.CanSend = v.Status == "draft" && guest != ""
		v.HasQR = v.Status == "draft" && rail == "qr"
		v.MenuSend = v.CanSend && v.CanLink
		v.ShowMenu = v.MenuSend || v.HasQR
		if !(v.Reason == "custom" && v.Note != "") {
			v.Note = ""
		}
		d.Requests = append(d.Requests, v)
	}
	return d, rows.Err()
}

// OverviewHandler serves GET /payments (payments_page).
func OverviewHandler(pool *pgxpool.Pool, getenv func(string) string, now func() time.Time) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		at := now()
		h, err := hostweb.Login(w, r, pool, getenv, at)
		if err != nil {
			fail(w, err)
			return
		}
		if h == nil {
			return
		}
		q := r.URL.Query()
		_, hasService := q["service"]
		_, hasStay := q["reservation_id"]
		if hasService || hasStay {
			target := "/payments/new"
			if r.URL.RawQuery != "" {
				target += "?" + r.URL.RawQuery
			}
			w.Header().Set("Location", target)
			w.WriteHeader(http.StatusSeeOther)
			return
		}
		d, err := loadOverview(r.Context(), pool, getenv, h.Workspace.ID)
		if err != nil {
			fail(w, err)
			return
		}
		render(w, r, pool, getenv, at, h, layout.Page{Title: "payments.title", BodyKind: "list", V2: true}, "payments", d)
	}
}

