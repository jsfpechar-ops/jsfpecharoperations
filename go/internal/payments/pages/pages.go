// REASONS in payment_request.py.
var reasons = []string{"repair", "extra_guest", "late_checkout", "cleaning", "damage", "custom"}

// NewHandler serves GET /payments/new (payments_new_page).
func NewHandler(pool *pgxpool.Pool, getenv func(string) string, now func() time.Time) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		at := now()
		h, err := hostweb.Login(w, r, pool, getenv, at)
		if err != nil {
			fail(w, err)
			return
		}
		if h == nil {
			return
		}
		ctx := r.Context()
		owner := h.Workspace.ID
		d := newData{Reasons: reasons}
		if raw, _ := lastQuery(r, "reservation_id"); asciiDigits(raw) {
			d.Selected, _ = strconv.ParseInt(raw, 10, 64)
		}
		list, err := listServices(ctx, pool, owner)
		if err != nil {
			fail(w, err)
			return
		}
		sid, _ := lastQuery(r, "service")
		d.Prefill = findService(list, sid)
		if d.Selected != 0 {
			var email string
			err := pool.QueryRow(ctx, stayEmailSQL, d.Selected, owner).Scan(&email)
			if err != nil && !errors.Is(err, pgx.ErrNoRows) {
				fail(w, err)
				return
			}
			d.GuestEmail = pyStrip(email)
		}
		if d.Stays, err = loadStays(ctx, pool, owner); err != nil {
			fail(w, err)
			return
		}
		bank, err := hasBankAccount(ctx, pool, owner)
		if err != nil {
			fail(w, err)
			return
		}
		d.NoBank = !bank
		render(w, r, pool, getenv, at, h, layout.Page{Title: "payments.new.title", BodyKind: "form", V2: true}, "payments_new", d)
	}
}

