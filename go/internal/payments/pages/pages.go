// ServiceAddHandler serves POST /payments/services (payment_service_add).
func ServiceAddHandler(pool *pgxpool.Pool, getenv func(string) string, now func() time.Time) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		at := now()
		if !hostweb.CSRF(w, r, getenv, at) {
			return
		}
		h, err := hostweb.Login(w, r, pool, getenv, at)
		if err != nil {
			fail(w, err)
			return
		}
		if h == nil {
			return
		}
		raw := pyStrip(lastForm(r, "amount_czk"))
		if !asciiDigits(raw) {
			backErr(w, r, "/payments", "payments.err.amount", "")
			return
		}
		amount, perr := strconv.ParseInt(raw, 10, 64)
		err = addService(r.Context(), pool, h.Workspace.ID, lastForm(r, "name"), amount, perr == nil)
		if errors.Is(err, errService) {
			backErr(w, r, "/payments", "payments.services.err", "")
			return
		}
		if err != nil {
			fail(w, err)
			return
		}
		backMsg(w, r, "/payments", "payments.services.saved")
	}
}

// ServiceDeleteHandler serves POST /payments/services/{id}/delete.
func ServiceDeleteHandler(pool *pgxpool.Pool, getenv func(string) string, now func() time.Time) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		at := now()
		if !hostweb.CSRF(w, r, getenv, at) {
			return
		}
		h, err := hostweb.Login(w, r, pool, getenv, at)
		if err != nil {
			fail(w, err)
			return
		}
		if h == nil {
			return
		}
		if err := removeService(r.Context(), pool, h.Workspace.ID, r.PathValue("id")); err != nil {
			fail(w, err)
			return
		}
		backMsg(w, r, "/payments", "payments.services.removed")
	}
}

// ---- GET /payments/requests/{id}/share --------------------------------------------

type shareData struct {
	Reason      string
	Amount      int64
	Link        string
	MailtoURL   string
	WhatsAppURL string
}

// ShareHandler serves GET /payments/requests/{id}/share (payment_request_share).
// links is payment_links.send. The mailto and WhatsApp URLs have a fixed
// scheme and a percent-encoded rest; the template writes them in a plain
// <a href> (html/template checks the scheme), never through a layout macro.
func ShareHandler(pool *pgxpool.Pool, getenv func(string) string, now func() time.Time, links payments.LinkSender) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		at := now()
		h, err := hostweb.Login(w, r, pool, getenv, at)
		if err != nil {
			fail(w, err)
			return
		}
		if h == nil {
			return
		}
		id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
		if err != nil {
			notFound(w) // FastAPI answers 422 for a non-integer id
			return
		}
		ctx := r.Context()
		var (
			owner, amount                int64
			rail, status, reason, linkID string
			email                        string
		)
		err = pool.QueryRow(ctx, shareRowSQL, id).Scan(&owner, &rail, &status, &reason, &amount, &linkID, &email)
		if err != nil && !errors.Is(err, pgx.ErrNoRows) {
			fail(w, err)
			return
		}
		open := status == "draft" || status == "sent" || status == "awaiting_payment"
		if err != nil || owner != h.Workspace.ID || rail != "card" || !open || linkID == "" {
			backErr(w, r, "/payments", "payments.err.invalid", "")
			return
		}
		link, err := links.SendPaymentLink(ctx, id)
		if errors.Is(err, payments.ErrStripeOff) {
			backErr(w, r, "/payments", "payments.err.stripe_off", "")
			return
		}
		if err != nil {
			fail(w, err)
			return
		}
		if link == "" {
			backErr(w, r, "/payments", "payments.err.not_ready", "stripe")
			return
		}
		lang := hostweb.Lang(r)
		label := cat.T(lang, "payments.reason."+reason, nil)
		message := cat.T(lang, "payments.share.message", map[string]any{"reason": label, "amount": amount, "link": link})
		subject := cat.T(lang, "payments.share.subject", nil)
		d := shareData{
			Reason:      reason,
			Amount:      amount,
			Link:        link,
			WhatsAppURL: "https://wa.me/?text=" + pyQuote(message),
			MailtoURL:   "mailto:" + pyQuote(pyStrip(email)) + "?subject=" + pyQuote(subject) + "&body=" + pyQuote(message),
		}
		render(w, r, pool, getenv, at, h, layout.Page{Title: "payments.share.title", BodyKind: "detail"}, "payments_share", d)
	}
}

