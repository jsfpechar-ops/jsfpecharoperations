// ConsentAcceptHandler serves POST /payments/consent (payments_consent_accept).
func ConsentAcceptHandler(pool *pgxpool.Pool, getenv func(string) string, now func() time.Time) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		at := now()
		if !hostweb.CSRF(w, r, getenv, at) {
			return
		}
		h, err := hostweb.Login(w, r, pool, getenv, at)
		if err != nil {
			fail(w, err)
			return
		}
		if h == nil {
			return
		}
		if stripeOff(getenv) {
			notFound(w)
			return
		}
		if lastForm(r, "agree") != "1" {
			backErr(w, r, "/payments/consent", "payments.err.consent", "")
			return
		}
		ctx := r.Context()
		owner := h.Workspace.ID
		done, err := consentAccepted(ctx, pool, owner)
		if err != nil {
			fail(w, err)
			return
		}
		if !done {
			var impersonator *int64
			if h.Impersonating {
				impersonator = &h.Account.ID
			}
			if _, err := pool.Exec(ctx, auditSQL, stampAt(at), h.Account.Username, consentAction,
				"version="+consentVersion, owner, h.Account.ID, impersonator); err != nil {
				fail(w, err)
				return
			}
		}
		backMsg(w, r, "/payments", "payments.consent.saved")
	}
}
