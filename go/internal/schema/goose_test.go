package schema

import (
	"context"
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/jackc/pgx/v5"
)

func writeFiles(t *testing.T, names ...string) string {
	t.Helper()
	dir := t.TempDir()
	for _, n := range names {
		if err := os.WriteFile(filepath.Join(dir, n), []byte("-- test\n"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func TestFilesGoodNames(t *testing.T) {
	dir := writeFiles(t, "00002_b.sql", "00001_a_b2.sql", "README.txt")
	got, err := Files(dir)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, []int{1, 2}) {
		t.Fatalf("got %v", got)
	}
}

func TestFilesBadName(t *testing.T) {
	for _, bad := range []string{"0001_a.sql", "00001-a.sql", "00001_A.sql"} {
		if _, err := Files(writeFiles(t, bad)); err == nil {
			t.Fatalf("%s: want error", bad)
		}
	}
}

func TestFilesDuplicateVersion(t *testing.T) {
	if _, err := Files(writeFiles(t, "00001_a.sql", "00001_b.sql")); err == nil {
		t.Fatal("duplicate version: want error")
	}
}

func TestPendingAgainstDatabase(t *testing.T) {
	url := os.Getenv("UBYHOST_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("UBYHOST_TEST_DATABASE_URL is not set")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)
	if _, err := conn.Exec(ctx, "DROP SCHEMA IF EXISTS go_goose_test CASCADE"); err != nil {
		t.Fatal(err)
	}
	defer func() {
		_, _ = conn.Exec(ctx, "DROP SCHEMA IF EXISTS go_goose_test CASCADE")
	}()
	if _, err := conn.Exec(ctx, "CREATE SCHEMA go_goose_test"); err != nil {
		t.Fatal(err)
	}
	if _, err := conn.Exec(ctx, "SET search_path TO go_goose_test"); err != nil {
		t.Fatal(err)
	}
	dir := writeFiles(t, "00001_a.sql", "00002_b.sql", "00003_c.sql", "00004_d.sql", "00005_e.sql")

	// No table yet: everything is pending.
	got, err := Pending(ctx, conn, dir)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, []int{1, 2, 3, 4, 5}) {
		t.Fatalf("no table: got %v", got)
	}

	if _, err := conn.Exec(ctx, `CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now())`); err != nil {
		t.Fatal(err)
	}
	// Version 1 applied; 2 newest row unapplied; 3 unapplied then re-applied; 0 is goose's marker.
	rows := [][2]any{{0, true}, {1, true}, {2, true}, {2, false}, {3, true}, {3, false}, {3, true}}
	for _, r := range rows {
		if _, err := conn.Exec(ctx, "INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, $2)", r[0], r[1]); err != nil {
			t.Fatal(err)
		}
	}
	got, err = Pending(ctx, conn, dir)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, []int{2, 4, 5}) {
		t.Fatalf("with rows: got %v", got)
	}
}
