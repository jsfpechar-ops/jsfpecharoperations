"""Goose files alone build the same PostgreSQL schema as Python's apply (brief 1472, plan S3).

Database A: `scripts/pg_schema.py apply` (the translated SQLite migrations, then
the goose files), which is how production was built. Database B: the Up section
of every file in App/migrations_pg, in version order, nothing else (the way the
Go test helpers build their databases), with goose_db_version rows written as
goose writes them. Both are dumped with `pg_dump --schema-only --no-owner` and
compared after normalise(); the version tables are compared row by row.

Documented differences, the only ones allowed:
- column order inside CREATE TABLE (a goose ADD COLUMN lands last): the column
  lines of each CREATE TABLE are sorted before the comparison, and a table whose
  order differs is reported as a warning, not a failure;
- schema_migrations.applied_at and goose_db_version.id/tstamp: written at apply
  time, so only (version, name) and (version_id, is_applied) are compared.
Not seen: rows outside the two version tables (backfills do nothing on an
empty database), sequence values, grants and ownership.

Runs when UBYHOST_TEST_DATABASE_URL is set (CI job test-postgres). With the URL
set, a missing pg_dump or a pg_dump older than the server fails the test: it is
never skipped for that reason. Every database it makes is dropped afterwards.
"""
from __future__ import annotations

import difflib
import os
import re
import shutil
import subprocess
import sys
import warnings
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

import pytest

APP_DIR = Path(__file__).resolve().parent.parent
GOOSE_DIR = APP_DIR / "migrations_pg"

_BASE_URL = os.environ.get("UBYHOST_TEST_DATABASE_URL", "")

pytestmark = pytest.mark.skipif(
    not _BASE_URL.startswith(("postgres://", "postgresql://")),
    reason="needs UBYHOST_TEST_DATABASE_URL (a disposable PostgreSQL)",
)

# The table goose v3 creates; the same text as db._goose_ensure_table.
GOOSE_TABLE_DDL = (
    "CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "
    "version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now())"
)
VERSION_ROWS_SQL = {
    "schema_migrations": "SELECT version, name FROM schema_migrations ORDER BY version",
    "goose_db_version": "SELECT version_id, is_applied FROM goose_db_version ORDER BY id",
}


def _url_for(database: str) -> str:
    parts = urlsplit(_BASE_URL)
    return urlunsplit((parts.scheme, parts.netloc, "/" + database, parts.query, ""))


def _admin():
    import psycopg

    return psycopg.connect(_BASE_URL, autocommit=True)


@pytest.fixture
def throwaway():
    made = []

    def make(suffix: str) -> str:
        name = f"ubyhost_test_goose_eq_{os.getpid()}_{suffix}"
        with _admin() as conn:
            conn.execute(f'DROP DATABASE IF EXISTS "{name}"')
            conn.execute(f'CREATE DATABASE "{name}"')
        made.append(name)
        return name

    yield make
    with _admin() as conn:
        for name in made:
            conn.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')


@pytest.fixture(scope="module")
def pg_dump():
    """pg_dump on PATH whose major version is at least the server's; fails otherwise."""
    binary = shutil.which("pg_dump")
    if not binary:
        pytest.fail("pg_dump is not on PATH; the goose equivalence test must run, not skip")
    out = subprocess.run([binary, "--version"], capture_output=True, text=True, timeout=30, check=False)
    match = re.search(r"\s(\d+)(?:\.\d+)?", out.stdout)
    assert out.returncode == 0 and match, f"cannot read the pg_dump version: {out.stdout}{out.stderr}"
    client = int(match.group(1))
    with _admin() as conn:
        server = int(conn.execute("SHOW server_version_num").fetchone()[0]) // 10000
    if client < server:
        pytest.fail(f"pg_dump {client} is older than PostgreSQL server {server}; install pg_dump {server} or newer")
    return binary


def _python_apply(database: str, data_dir: Path) -> None:
    env = {
        key: value for key, value in os.environ.items()
        if key not in {"UBYHOST_DB", "UBYHOST_DATABASE_URL", "UBYHOST_TEST_DATABASE_URL", "UBYHOST_DATA_DIR"}
    }
    env.update(UBYHOST_DATABASE_URL=_url_for(database), UBYHOST_DATA_DIR=str(data_dir))
    result = subprocess.run(
        [sys.executable, "scripts/pg_schema.py", "apply", "--expect-database", database],
        cwd=APP_DIR, env=env, capture_output=True, text=True, timeout=300, check=False,
    )
    assert result.returncode == 0, (result.stdout + result.stderr)[-3000:]


def _goose_only_apply(database: str) -> None:
    import psycopg

    files = sorted(GOOSE_DIR.glob("*.sql"))
    assert files, "no goose files found"
    with psycopg.connect(_url_for(database), autocommit=True) as conn:
        conn.execute(GOOSE_TABLE_DDL)
        conn.execute("INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)")
        for path in files:
            text = path.read_text(encoding="utf-8")
            assert "-- +goose Up" in text, f"{path.name} has no '-- +goose Up' line"
            up = text.split("-- +goose Up", 1)[1].split("-- +goose Down", 1)[0]
            with conn.transaction():
                conn.execute(up)
                conn.execute(
                    "INSERT INTO goose_db_version (version_id, is_applied) VALUES (%s, true)",
                    (int(path.name[:5]),),
                )


def _dump(binary: str, database: str) -> str:
    result = subprocess.run(
        [binary, "--schema-only", "--no-owner", "--dbname", _url_for(database)],
        capture_output=True, text=True, timeout=300, check=False,
    )
    assert result.returncode == 0, result.stderr[-3000:]
    return result.stdout


def normalise(dump: str) -> tuple[list[str], dict[str, list[str]]]:
    """Comparable lines of a schema dump, plus the column order of every table.

    Drops comment lines, blank lines and the \\restrict/\\unrestrict lines (a
    random key per dump). Inside each CREATE TABLE block the column lines lose
    their trailing comma and are sorted, so only column order is ignored.
    """
    lines: list[str] = []
    order: dict[str, list[str]] = {}
    table = None
    columns: list[str] = []
    for raw in dump.splitlines():
        line = raw.rstrip()
        if not line.strip() or line.lstrip().startswith("--") or line.startswith(("\\restrict", "\\unrestrict")):
            continue
        if table is None:
            match = re.match(r"CREATE TABLE (\S+) \($", line)
            if match:
                table, columns = match.group(1), []
            lines.append(line)
        elif line == ");":
            order[table] = [column.split()[0] for column in columns]
            lines.extend(sorted(columns))
            lines.append(line)
            table = None
        else:
            columns.append(line.removesuffix(","))
    assert table is None, f"dump ends inside CREATE TABLE {table}"
    return lines, order


def _version_rows(database: str) -> dict:
    import psycopg

    with psycopg.connect(_url_for(database), autocommit=True) as conn:
        return {name: [tuple(row) for row in conn.execute(sql).fetchall()] for name, sql in VERSION_ROWS_SQL.items()}


def test_goose_files_alone_build_the_python_applied_schema(throwaway, pg_dump, tmp_path):
    python_db, goose_db = throwaway("a"), throwaway("b")
    _python_apply(python_db, tmp_path)
    _goose_only_apply(goose_db)

    want, want_order = normalise(_dump(pg_dump, python_db))
    got, got_order = normalise(_dump(pg_dump, goose_db))
    moved = sorted(name for name in want_order.keys() & got_order.keys() if want_order[name] != got_order[name])
    if moved:
        warnings.warn(f"column order differs (allowed) in: {', '.join(moved)}", stacklevel=1)
    diff = list(difflib.unified_diff(want, got, "python_apply", "goose_only", n=2, lineterm=""))
    assert not diff, "goose-only schema differs from Python's apply:\n" + "\n".join(diff[:200])

    assert _version_rows(goose_db) == _version_rows(python_db)
