"""Dump the i18n strings the Go completion mail port needs, for every language.

Run from App/ with the project venv:

    /var/tmp/ubyvenv/bin/python scripts/go_mailnotify_completion_i18n.py

Writes go/internal/mailnotify/completion_i18n_strings.json (embedded with go:embed by
go/internal/mailnotify/completion_i18n.go). It is a third dump next to i18n_strings.json
and doorcode_i18n_strings.json, which are left untouched. Only the guest keys that
build_completion reads are dumped: its own copy, the stay panel, the fee block it shares
with the door-code mail, the door-code block and the guest footer.
A language that lacks a key is left out of its table on purpose: the Go lookup then
falls back to the default language exactly as ``i18n.translator`` does.
"""
from __future__ import annotations

import json
import os
import sys

APP_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
REPO_DIR = os.path.abspath(os.path.join(APP_DIR, ".."))
OUT = os.path.join(REPO_DIR, "go", "internal", "mailnotify", "completion_i18n_strings.json")
sys.path.insert(0, APP_DIR)

from app import i18n  # noqa: E402

# Guest keys read by build_completion, _completion_facts, _fee_block, the door-code block
# and _guest_footer_lines (plus property_label's fallback).
GUEST_KEYS = [
    "mail_completion_subject",
    "mail_completion_subject_fee",
    "mail_completion_intro",
    "mail_completion_intro_fee",
    "mail_completion_heading",
    "mail_completion_heading_fee",
    "mail_completion_preheader",
    "mail_completion_preheader_fee",
    "mail_completion_note",
    "mail_completion_guests_label",
    "mail_completion_guests_value",
    "mail_completion_checkin_label",
    "mail_completion_checkout_label",
    "mail_completion_checkin_value",
    "mail_completion_checkout_value",
    "mail_completion_panel_title",
    "mail_completion_host_action",
    "mail_completion_sent_title",
    "mail_completion_sent_doc_label",
    "mail_completion_sent_unnamed",
    "mail_completion_fee_heading",
    "mail_completion_fee_total",
    "mail_completion_fee_calc_title",
    "mail_completion_fee_once",
    "mail_completion_fee_already",
    "fee_guest_n",
    "fee_person_line",
    "fee_no_rails",
    "fee_rail_iban",
    "fee_payee",
    "fee_iban",
    "fee_amount",
    "fee_amount_label",
    "fee_vs_label",
    "fee_qr_alt",
    "fee_revolut_button",
    "fee_rail_cash",
    "fee_cash_default",
    "door_code_title",
    "door_code_times",
    "door_code_first_use",
    "mail_guest_footer_about",
    "mail_guest_footer_why",
    "mail_guest_footer_host_label",
    "mail_guest_footer_help",
    "mail_link_fallback",
    "mail_property_fallback",
]


def _pick_guest(catalogue: dict) -> dict:
    return {lang: {k: catalogue[lang][k] for k in GUEST_KEYS if k in catalogue[lang]}
            for lang in sorted(catalogue)}


def main() -> None:
    doc = {
        "_comment": "Generated by App/scripts/go_mailnotify_completion_i18n.py. Do not edit by hand.",
        "guest": _pick_guest(i18n.STRINGS),
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=1, sort_keys=True)
        fh.write("\n")
    missing = {
        lang: [k for k in GUEST_KEYS if k not in i18n.STRINGS[lang]]
        for lang in i18n.LANGUAGES
    }
    print("wrote", OUT)
    print("guest keys missing per language:", {k: v for k, v in missing.items() if v})


if __name__ == "__main__":
    main()
